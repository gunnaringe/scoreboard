// "auto" follows the browser: any Norwegian (nb/nn/no) gets Norwegian.
function browserLang() {
    return (navigator.languages || [navigator.language]).some((l) => /^(nb|nn|no)\b/i.test(l)) ? 'no' : 'en';
}

export function currentLang() {
    const v = localStorage.getItem('lang');
    if (I18N[v]) return v;
    // The operator's default language (branding), else whatever the browser prefers.
    const def = document.querySelector('meta[name=default-lang]')?.content;
    return I18N[def] ? def : browserLang();
}

// Locale for dates and times.
export function locale() {
    return currentLang() === 'no' ? 'nb-NO' : 'en-GB';
}

export function t(key, vars) {
    let s = I18N[currentLang()][key] ?? I18N.en[key] ?? key;
    if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
    return s;
}

export function applyI18n() {
    document.documentElement.lang = currentLang() === 'no' ? 'nb' : 'en';
}
